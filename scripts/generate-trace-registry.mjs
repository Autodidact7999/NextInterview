import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { format } from "prettier";

const root = process.cwd();
const problemsDirectory = path.join(
  root,
  "src/content/visualizations/problems",
);
const catalogFile = path.join(
  root,
  "src/content/visualizations/catalog.generated.ts",
);
const loadersFile = path.join(
  root,
  "src/content/visualizations/loaders.generated.ts",
);
const linksFile = path.join(
  root,
  "src/content/visualizations/links.generated.ts",
);

const folders = (await readdir(problemsDirectory, { withFileTypes: true }))
  .filter(
    (entry) => entry.isDirectory() && /^\d{4}-[a-z0-9-]+$/.test(entry.name),
  )
  .map((entry) => entry.name)
  .sort((a, b) => Number(a.slice(0, 4)) - Number(b.slice(0, 4)));

const modules = await Promise.all(
  folders.map(async (folder) => ({
    folder,
    definitionHasDefault: /export\s+default\b/.test(
      await readFile(
        path.join(problemsDirectory, folder, "definition.ts"),
        "utf8",
      ),
    ),
    runtimeHasDefault: /export\s+default\b/.test(
      await readFile(
        path.join(problemsDirectory, folder, "runtime.ts"),
        "utf8",
      ),
    ),
  })),
);

const catalogImports = modules
  .map(({ folder, definitionHasDefault }, index) =>
    definitionHasDefault
      ? `import definition${index} from "@/content/visualizations/problems/${folder}/definition";`
      : `import { definition as definition${index} } from "@/content/visualizations/problems/${folder}/definition";`,
  )
  .join("\n");
const definitions = folders
  .map((_, index) => `  definition${index},`)
  .join("\n");

const catalog = await format(
  `/* This file is generated by scripts/generate-trace-registry.mjs. */
${catalogImports}

import type { TraceProblemDefinition } from "@/lib/visualizer/types";

export const traceDefinitions = [
${definitions}
] as const satisfies readonly TraceProblemDefinition[];

`,
  { parser: "typescript" },
);

const linkLines = folders
  .map((folder) => `  ${Number(folder.slice(0, 4))}: "${folder.slice(5)}",`)
  .join("\n");
const links = await format(
  `/* This file is generated by scripts/generate-trace-registry.mjs. */
export const traceSlugByLc: Readonly<Record<number, string>> = {
${linkLines}
};
`,
  { parser: "typescript" },
);

const loaderLines = modules
  .map(({ folder, runtimeHasDefault }) => {
    const slug = folder.slice(5);
    const exportName = runtimeHasDefault ? "default" : "runtime";
    return `  "${slug}": () => import("@/content/visualizations/problems/${folder}/runtime").then((module) => ({ runtime: module.${exportName} })),`;
  })
  .join("\n");
const loaders = await format(
  `/* This file is generated by scripts/generate-trace-registry.mjs. */
import type { TraceProblemRuntime } from "@/lib/visualizer/types";

export type TraceRuntimeModule = { runtime: TraceProblemRuntime };

export const traceRuntimeLoaders: Readonly<
  Record<string, () => Promise<TraceRuntimeModule>>
> = {
${loaderLines}
};
`,
  { parser: "typescript" },
);

async function update(file, content) {
  if (process.argv.includes("--check")) {
    let existing = "";
    try {
      existing = await readFile(file, "utf8");
    } catch {
      // The comparison below reports the actionable error.
    }
    if (existing !== content) {
      console.error(
        `${path.relative(root, file)} is stale. Run npm run trace:generate.`,
      );
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(file, content, "utf8");
}

await Promise.all([
  update(catalogFile, catalog),
  update(loadersFile, loaders),
  update(linksFile, links),
]);
